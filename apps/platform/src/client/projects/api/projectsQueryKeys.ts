export const PROJECTS_QUERY_KEY = ['projects'] as const;

/**
 * Ключ карточки одного проекта — **потомок** ключа галереи, и это несущее свойство, а не оформление
 * (задача 0095).
 *
 * До появления `GET /api/v1/projects/:id` шапка редактора и галерея сидели на одном ключе `['projects']`:
 * запрос был буквально один, поэтому переименование, инвалидирующее этот ключ, обновляло сразу оба места.
 * Открытие проекта с ручки списка ушло, запроса стало два — и связь пришлось чем-то удержать. Держит её
 * вложенность ключа: react-query сопоставляет ключи **по префиксу**, поэтому уже существующие
 * `invalidateQueries({ queryKey: PROJECTS_QUERY_KEY })` в модалках переименования, удаления и создания
 * достают и карточку тоже — ни одну из них трогать не пришлось.
 *
 * Сломать это можно ровно одним способом — сделав ключ карточки не потомком, а соседом; тогда шапка
 * редактора застынет со старым именем до перезагрузки. На этот случай есть `projectsQueryKeys.test.ts`.
 */
export const projectQueryKey = (projectId: string): readonly string[] => [...PROJECTS_QUERY_KEY, 'detail', projectId];
