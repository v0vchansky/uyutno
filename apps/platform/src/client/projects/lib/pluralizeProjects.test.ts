import { pluralizeProjects } from './pluralizeProjects';

describe('pluralizeProjects', () => {
  it.each([
    [0, '0 проектов'],
    [1, '1 проект'],
    [2, '2 проекта'],
    [4, '4 проекта'],
    [5, '5 проектов'],
    [10, '10 проектов'],
    [11, '11 проектов'],
    [12, '12 проектов'],
    [14, '14 проектов'],
    [15, '15 проектов'],
    [21, '21 проект'],
    [22, '22 проекта'],
    [25, '25 проектов'],
    [101, '101 проект'],
    [102, '102 проекта'],
    [111, '111 проектов'],
    [125, '125 проектов'],
  ])('%s -> %s', (count, expected) => {
    expect(pluralizeProjects(count)).toBe(expected);
  });
});
