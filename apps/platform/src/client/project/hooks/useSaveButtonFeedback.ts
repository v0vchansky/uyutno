import type { PersistenceState } from '@uyutno/planner';
import { useEffect, useState } from 'react';

/**
 * Что показывает кнопка «Сохранить» прямо сейчас (задача 0090): обычный вид, «идёт запись», подтверждение.
 * Это **не** копия `PersistenceStatus`: у кнопки нет ни офлайна, ни ошибки — их носители другие (тихая
 * иконка и модалка, задача 0084), — зато есть кадры, которых в движке нет вовсе, потому что живут они
 * дольше самого сохранения.
 */
export type SaveButtonPhase = 'idle' | 'saving' | 'saved';

/**
 * Сколько «Сохраняем…» держится **после** того, как запись уже кончилась.
 *
 * Число взято из измерения, а не из головы: реальный `PUT …/document` на dev-стенде возвращается за 9–24 мс
 * (медиана ~11 мс) — меньше одного кадра экрана в 16.7 мс. Кнопка честно переходила в «идёт запись» ещё с
 * задачи 0084, но человек этого кадра не видел, и жалоба «нет никакого фидбэка» была про длительность, а не
 * про отсутствие состояния.
 *
 * Отсюда и форма правила: не «спиннер ровно столько-то», а «спиннер плюс хвост». Спиннер виден **не меньше**
 * этого срока при любой скорости сервера, и почти ровно столько же при мгновенном ответе: 450 мс хвоста плюс
 * ~11 мс запроса дают ~460 мс — середину коридора 400–600 мс. Ниже ~400 мс кадр читается как дёрганье
 * интерфейса, а не как ответ на нажатие; выше ~600 мс он начинает добавлять выдуманное ожидание к операции,
 * которая на деле мгновенна. Хвост постоянный, поэтому медленный сервер не удлиняет его пропорционально.
 */
export const SAVING_TAIL_MS = 450;

/**
 * Сколько держится галочка. Секунда с небольшим: меньше — человек, уже отведший глаза от кнопки, не успевает
 * вернуться и прочитать; больше — подтверждение начинает выглядеть как новое состояние кнопки, а не как
 * ответ на действие. Весь цикл нажатия укладывается в ~1.7 с.
 */
export const SAVED_HOLD_MS = 1_200;

/** Успех, который кнопка обязана отпраздновать: ручной Save (кнопка или Ctrl+S) с известным временем. */
const manualSaveAt = (state: PersistenceState | null): number | null =>
  state !== null && state.status === 'saved' && state.savedReason === 'manual' ? state.savedAt : null;

/** Пройденные границы цикла для конкретного успеха: 1 — хвост спиннера кончился, 2 — галочка отжила своё. */
interface FeedbackCycle {
  savedAt: number;
  step: 1 | 2;
}

/**
 * Кадр кнопки «Сохранить» из состояния сохранения (задача 0090).
 *
 * **Обратная связь принадлежит ручному сохранению.** Галочку и хвост спиннера получает только `manual` —
 * кнопка и Ctrl+S, то есть действие человека. Фоновый автосейв идёт как раньше: принцип макета —
 * «ручное действие → заметный ответ, фоновое → тихая иконка или молчание» (handoff, «Индикатор состояния
 * сохранения»), и держать «Сохраняем…» лишние полсекунды раз в минуту посреди рисования значило бы шуметь
 * там, где человек ничего не просил. Отдельной проводки от кнопки для этого не нужно: причину последнего
 * успеха движок называет сам (`savedReason`).
 *
 * Отказ и офлайн кадра не получают вовсе — обратная связь снимается сразу, а ошибку показывают её
 * собственные носители: модалка ручного Save и тихая иконка (задача 0084).
 *
 * Часы читаются только в эффекте и в таймерах: рендер обязан быть чистым, а `Date.now()` в нём — нет.
 * Поэтому состояние хранит не время, а **пройденные границы** цикла: пока для текущего успеха не сработал
 * ни один таймер, кнопка ещё в спиннере, и кадр не мигает обычным видом между ответом сервера и хвостом.
 */
export const useSaveButtonFeedback = (state: PersistenceState | null): SaveButtonPhase => {
  const [cycle, setCycle] = useState<FeedbackCycle | null>(null);

  const status = state?.status ?? null;
  const savedAt = manualSaveAt(state);

  useEffect(() => {
    if (savedAt === null) return;

    /*
     * Движок о конце кадра не сообщит — событий там больше не будет, а показанное обязано смениться. Оба
     * срока считаются от `savedAt`, а не от «сейчас»: снимок мог доехать до React позже самого сохранения.
     */
    const timers = ([1, 2] as const).map(step =>
      setTimeout(
        () => setCycle({ savedAt, step }),
        Math.max(0, savedAt + SAVING_TAIL_MS + (step === 2 ? SAVED_HOLD_MS : 0) - Date.now()),
      ),
    );

    return () => {
      for (const timer of timers) clearTimeout(timer);
    };
  }, [savedAt]);

  if (status === 'saving') return 'saving';
  if (savedAt === null) return 'idle';
  // Цикл этого успеха ещё не начался или идёт хвост спиннера — кнопка остаётся в «Сохраняем…».
  if (cycle === null || cycle.savedAt !== savedAt) return 'saving';
  return cycle.step === 1 ? 'saved' : 'idle';
};
