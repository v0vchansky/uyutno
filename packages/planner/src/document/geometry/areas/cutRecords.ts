import type { Id } from '../../id';

/** Вертикальная грань зоны как ребро по концам-точкам; тождество записи — **неупорядоченная** пара (ADR 0017 C9). */
export interface CutEdge {
  a: Id;
  b: Id;
}

/**
 * Ключ неупорядоченной пары id — тождество записи `cuts[]` между пересборками. Разделитель `|` в uuid v7
 * не встречается, поэтому склейка однозначна.
 */
export const cutKey = (a: Id, b: Id): string => (a < b ? `${a}|${b}` : `${b}|${a}`);

/** Зона в виде, достаточном для вычисления её вертикальных граней. */
export interface AreaEdgeSet {
  /**
   * Интерьерные **участки** рёбер зоны (`classifyAreaEdges` → `kind: 'interior'`), концы разрешены в id
   * точек этажа. Не рёбра целиком: ребро зоны может идти по грани и продолжаться за её конец через
   * интерьер, и грань нужна ровно на интерьерном куске. Концы участка — либо точка зоны, либо конец
   * грани контура, то есть всегда хранимая точка; разрешение координаты в id — стадия `normalize` (0069)
   * по тождеству квантованной координаты.
   */
  interior: readonly CutEdge[];
}

/**
 * Набор записей `cuts[]`, которые должны существовать при данном наборе зон: интерьерные участки рёбер
 * всех зон, дедуплицированные по неупорядоченной паре id. Порядок детерминирован — первое вхождение в
 * порядке `areas` и участков внутри зоны. Вырожденные (`a === b`) пропускаются.
 *
 * **Решение (1) эпика 0066 — у записи нет хранимого владельца, владение вычисляется.** Участок, общий для
 * двух касающихся зон, встречается в наборе дважды и даёт **одну** запись: вторая зона переиспользует
 * существующую — это и есть «владелец = записавшая первой» (ADR 0017 C9), только без поля-владельца.
 * Запись жива, пока **хотя бы одна** зона держит этот участок как интерьерный; как только не держит ни
 * одна (одна из касающихся зон исчезла, а у второй участок стал стеновым; обе исчезли; зона отбракована),
 * пара выпадает из `requiredCuts` и запись удаляется в `normalize`. Следствие: при исчезновении одной из
 * двух касающихся зон запись переживает пересборку **вместе со своим id и материалом**, если участок
 * остался интерьерным у выжившей; высота грани пересчитывается — она производная (максимум высот соседних
 * зон, иначе высота стен), а не хранимая.
 */
export const requiredCuts = (areas: readonly AreaEdgeSet[]): CutEdge[] => {
  const result: CutEdge[] = [];
  const seen = new Set<string>();
  for (const area of areas) {
    for (const edge of area.interior) {
      if (edge.a === edge.b) continue;
      const key = cutKey(edge.a, edge.b);
      if (seen.has(key)) continue;
      seen.add(key);
      result.push({ a: edge.a, b: edge.b });
    }
  }
  return result;
};

/**
 * Сведение хранимых записей `cuts[]` к нужному набору (стадия `normalize`, 0069): для каждой нужной пары —
 * прежняя запись с тем же ключом (**по ссылке**, со своим id, порядком концов и материалом: спека 02 «У грани
 * собственный материал… он сохраняется вместе с зоной и переживает пересборку»), иначе новая через `create`.
 * Записи, не попавшие в `required`, отбрасываются — «запись без зоны-владельца удаляется в `normalize`»
 * (ADR 0017 C9).
 *
 * Полная регенерация набора из рёбер всех зон с переносом данных по совпадению концов — как у референса
 * (`resetCuts`). **Расхождение осознанное:** референс создаёт `CCut` только при найденном совпадении, то
 * есть ребро без старого донора записи не порождает вовсе, а два старых cut'а на одну сторону дают дубль
 * (у внутреннего цикла нет `break`). У нас новая пара получает новую запись через `create` — иначе грань
 * впервые нарисованной зоны не появилась бы никогда, — а дубли ключа среди `existing` схлопываются:
 * донором становится первый.
 *
 * **Обязательство вызывающего.** Функция всегда возвращает **новый массив** (`required.map`) в порядке
 * `required` — то есть порядок выхода задаётся набором зон, а не историей правок, и ссылочного равенства
 * с `existing` не бывает даже на неизменившемся наборе. Ссылочно совпадают только элементы. Поэтому
 * `normalize` обязан писать результат в черновик **только при фактическом изменении набора** (сравнение
 * поэлементно, как и для контуров): наивное `layout.cuts = reconcileCuts(...)` сломало бы идемпотентность
 * `normalize` по ссылке, на которой держится restore undo/redo.
 */
export const reconcileCuts = <T extends CutEdge>(
  existing: readonly T[],
  required: readonly CutEdge[],
  create: (edge: CutEdge) => T,
): T[] => {
  const donors = new Map<string, T>();
  for (const record of existing) {
    const key = cutKey(record.a, record.b);
    if (!donors.has(key)) donors.set(key, record);
  }
  return required.map(edge => donors.get(cutKey(edge.a, edge.b)) ?? create(edge));
};
