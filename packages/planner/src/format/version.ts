/**
 * Идентификатор формата, цепочка миграций и **выведенный из неё** номер текущей версии (ADR 0021,
 * «Версии, парсер, миграции»).
 *
 * Модуль намеренно безимпортный: его читает и `document/PlannerDocument.ts` (форма документа), и весь
 * `format/`, и через них — серверный процесс. Любая зависимость здесь размножилась бы по всему графу.
 */

/** JSON-значение в том виде, в каком приезжает из колонки `projects.document` / localStorage. */
export type JsonValue = string | number | boolean | null | JsonValue[] | { [key: string]: JsonValue };
export type JsonObject = { [key: string]: JsonValue };

export const DOCUMENT_FORMAT = 'uyutno.planner';
export type DocumentFormat = typeof DOCUMENT_FORMAT;

/**
 * Шаг цепочки: поднимает конверт **на одну** версию вверх, работая с сырым JSON (типизированного
 * документа на этом этапе ещё нет — старая версия по определению не соответствует текущей схеме).
 * Обязан быть чистым и детерминированным: на нём держится безвредность гонки двух одновременных
 * серверных чтений (ADR 0021, «Что важно знать»).
 */
export type Migration = (raw: JsonObject) => JsonObject;

/**
 * Цепочка миграций формата. Индекс — это версия входа: `MIGRATIONS[0]` поднимает документ с версии 1
 * на 2, `MIGRATIONS[1]` — с 2 на 3, и так далее. В v0 цепочка пуста.
 *
 * Дописывать шаг — значит поднять версию: константа ниже пересчитается сама, руками её никто не трогает.
 * Обратное тоже верно и ровно в этом смысл правила: нельзя поднять номер, забыв шаг.
 */
export const MIGRATIONS: readonly Migration[] = [];

/**
 * Текущая версия формата = длина цепочки + 1.
 *
 * ADR 0021 формулирует правило как «текущая версия = длина цепочки»; буквально это давало бы `0` на
 * пустой цепочке, тогда как первая, ещё ни разу не мигрировавшая версия формата — `1` (ADR 0016 B6,
 * и именно `1` лежит во всех документах, которые уже умеет писать код). Смысл правила — связать номер
 * с цепочкой намертво — сохранён: шаг `i` мигрирует `i → i + 1`, поэтому число версий на единицу больше
 * числа переходов между ними. Уточнение зафиксировано в «Заметках» задачи 0079.
 */
export const versionOf = (migrations: readonly Migration[]): number => migrations.length + 1;

export const DOCUMENT_VERSION = versionOf(MIGRATIONS);
